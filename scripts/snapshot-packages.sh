#!/usr/bin/env bash
# snapshot-packages.sh — dump what is actually installed on this box.
#
# Writes packages.installed.txt (repo root): the machine's view of apt, snap,
# flatpak, npm -g and uv tools, in the same order as the curated packages.txt.
# Diff the two to find manifest drift:
#
#   ./scripts/snapshot-packages.sh && git diff packages.installed.txt
#
# The snapshot is generated — never hand-edit it. Change packages.txt instead,
# or record a new app in the section it belongs to. No sudo needed.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
out="$repo_root/packages.installed.txt"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

have() { command -v "$1" >/dev/null 2>&1; }
section() { printf '\n## %s\n' "$*"; }

# Every manually installed package as "name<TAB>version<TAB>from_repo(1|0)".
# apt-cache policy prints a repository URI only for packages available from a
# repo; a local .deb has nothing but the /var/lib/dpkg/status line.
collect_apt() {
  have apt-mark && have apt-cache || return 0
  apt-mark showmanual | sort | xargs apt-cache policy 2>/dev/null | awk '
    function flush() {
      if (pkg != "" && ver != "") printf "%s\t%s\t%d\n", pkg, ver, repo
    }
    /^[^[:space:]]/ { flush(); pkg = $0; sub(/:$/, "", pkg); ver = ""; repo = 0; next }
    /^  Installed: / { ver = $2 }
    /^[[:space:]]+[0-9]+ https?:\/\// { repo = 1 }
    END { flush() }
  ' | sort
}

{
  printf '# packages.installed.txt — GENERATED by scripts/snapshot-packages.sh, do not edit.\n'
  printf '# Snapshot: %s on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$(hostname)"
  printf '# Distro:   %s\n' "$(grep -hE '^(NAME|VERSION_ID)=' /etc/os-release 2>/dev/null | cut -d= -f2- | tr -d '"' | paste -sd' ' -)"

  collect_apt >"$tmp"

  section "apt — manual, from a repository"
  awk -F'\t' '$3 == 1 { printf "%-32s %s\n", $1, $2 }' "$tmp"

  section "apt — local .debs (no repository)"
  awk -F'\t' '$3 == 0 { printf "%-32s %s\n", $1, $2 }' "$tmp"

  section "apt — third-party sources"
  grep -hs -E '^(URIs|deb )' /etc/apt/sources.list /etc/apt/sources.list.d/*.sources \
    /etc/apt/sources.list.d/*.list 2>/dev/null | sed 's/[[:space:]]\+/ /g' | sort -u || true

  section "snap"
  if have snap; then
    snap list 2>/dev/null | tail -n +2 | awk '{ printf "%-32s %s\n", $1, $2 }' | sort
  else
    echo '(snap not installed)'
  fi

  section "flatpak — apps"
  if have flatpak; then
    flatpak list --app --columns=application,version 2>/dev/null \
      | awk -F'\t' '{ printf "%-34s %s\n", $1, $2 }' | sort -u
  else
    echo '(flatpak not installed)'
  fi

  section "npm -g"
  if have npm; then
    npm_root="$(npm root -g 2>/dev/null || true)"
    npm ls -g --depth=0 --parseable 2>/dev/null | tail -n +2 | while read -r p; do
      name="${p#"$npm_root"/}"
      ver="$(node -p "require('$p/package.json').version" 2>/dev/null || echo '?')"
      printf '%-40s %s\n' "$name" "$ver"
    done | sort
  else
    echo '(npm not installed)'
  fi

  section "uv tools"
  if have uv; then
    uv tool list 2>/dev/null | grep -v '^- ' | sort
  else
    echo '(uv not installed)'
  fi
} >"$out"

printf 'wrote %s (%s lines)\n' "${out#"$repo_root"/}" "$(wc -l <"$out")"
